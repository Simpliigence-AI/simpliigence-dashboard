/** The five fields the scorecard grades. */
export const SCORE_FIELDS = ['problem', 'solution', 'outcomes', 'whatWeDid', 'salesforce'] as const;
export const SCORE_LABEL: Record<(typeof SCORE_FIELDS)[number], string> = {
  problem: 'Business problem',
  solution: 'Solution',
  outcomes: 'Outcomes',
  whatWeDid: 'What we’ve done',
  salesforce: 'Salesforce products',
};

/** A field counts once it has at least one real line (not a "Pending" placeholder). */
export function isFilled(cs: CaseStudy, f: (typeof SCORE_FIELDS)[number]): boolean {
  // Non-Salesforce work (RPA, mobile) still has a product stack to show.
  const v = f === 'salesforce' ? [...cs.salesforce, ...cs.stack] : cs[f];
  return v.some((line) => line.trim() && !/^pending/i.test(line.trim()));
}

export function completeness(cs: CaseStudy): number {
  return SCORE_FIELDS.filter((f) => isFilled(cs, f)).length;
}
